import { useState } from 'react';
import { HaltScreen } from './HaltScreen';
import { getExecution, transitionExecution } from '../lib/executionState';
import { EvidenceReport } from './EvidenceReport';
import { ReplayViewer } from './ReplayViewer';

export function HaltController({ onDismiss }: { onDismiss: () => void }) {
  const reqId = 'REQ_908PIR0';
  const [globalStatus, setGlobalStatus] = useState(() => getExecution(reqId).status);
  const [evidenceReceipt, setEvidenceReceipt] = useState<any>(null);
  const [actionState, setActionState] = useState<{ status: 'idle' | 'loading' | 'success' | 'error', message?: string, details?: string }>({ status: 'idle' });
  const [showEvidence, setShowEvidence] = useState(false);
  const [showReplay, setShowReplay] = useState(false);

  const timelineData = [
    { step: '1. IDENTITY', status: '✓ Verified' },
    { step: '2. RUNTIME', status: '✓ Attested' },
    { step: '3. TOKEN CREATION', status: '✓ Created' },
    { step: '4. JOE ANALYSIS', status: '✓ Validated' },
    { step: '5. ALITA SEC REVIEW', status: '✓ Validated' },
    { step: '6. FIREFLY MEMORY', status: '✓ Authorized' },
    { step: '7. CONSENSUS', status: '✓ Reached' },
    { step: '8. GOVERNANCE', status: '✓ Approved' },
    { step: '9. EXECUTION GATE 3', status: '✓ Passed (99%)' }
  ];

  const gate3Data = {
    joe: { score: 0.3333, proofValid: true, receiptId: `REC_J_${Math.floor(Math.random() * 1000)}` },
    alita: { score: 0.3333, proofValid: true, receiptId: `REC_A_${Math.floor(Math.random() * 1000)}` },
    governance: { score: 0.3333, proofValid: true, receiptId: `REC_G_${Math.floor(Math.random() * 1000)}` },
    firefly: { score: 0.20, proofValid: true, receiptId: `REC_F_${Math.floor(Math.random() * 1000)}` }
  };

  // Simulate calling the SWI API Gateway.
  const handleBackendAction = async (actionEndpoint: string, payload?: any) => {
    if (actionEndpoint === 'evidence') {
      setShowEvidence(true);
      return;
    }
    
    if (actionEndpoint === 'replay') {
      setShowReplay(true);
      return;
    }

    setActionState({ status: 'loading', message: `POST /api/seam/actions/${actionEndpoint}` });
    
    // Simulate backend processing pipeline
    await new Promise(resolve => setTimeout(resolve, 1500));
    
    try {
      if (actionEndpoint === 'approve' || actionEndpoint === 'cancel') {
        const execution = transitionExecution(reqId, actionEndpoint as any, gate3Data);
        setGlobalStatus(execution.status);
      }
    } catch (e: any) {
      setActionState({ status: 'error', message: 'EXECUTION HALTED', details: e.message });
      return;
    }

    
    // The canonical evidence generated by the trusted backend Evidence Service
    const receipt = {
      receipt_id: `REC_${Math.floor(Math.random() * 1000000)}`,
      execution_id: reqId,
      action: actionEndpoint.toUpperCase(),
      status: "SUCCESS",
      governance: {
        decision: "APPROVED",
        policy_version: "v2.1.0"
      },
      runtime: {
        binding: "PASS",
        attestation: "PASS"
      },
      security_maze: {
        decision: "PASS"
      },
      firefly: {
        snapshot_id: `FF_${Math.floor(Math.random() * 10000)}`
      },
      files: {
        pdf: `${actionEndpoint}.pdf`,
        json: `${actionEndpoint}.json`
      },
      signature: `0x${Array.from({length: 32}, () => Math.floor(Math.random()*16).toString(16)).join('')}`,
      hash: `0x${Array.from({length: 32}, () => Math.floor(Math.random()*16).toString(16)).join('')}`
    };

    setEvidenceReceipt(receipt);
    setActionState({ status: 'success', message: `${actionEndpoint.toUpperCase()} COMPLETE` });

    if (actionEndpoint === 'approve' || actionEndpoint === 'cancel') {
      setTimeout(onDismiss, 3000);
    }
  };

  return (
    <>
      <HaltScreen 
        reqId={reqId}
        globalStatus={globalStatus}
        actionState={actionState}
        evidenceReceipt={evidenceReceipt}
        timelineData={timelineData}
        gate3Data={gate3Data}
        onApprove={() => handleBackendAction('approve')}
        onModify={() => handleBackendAction('modify', { intent: "Safely backup and delete selected files" })}
        onCancel={() => handleBackendAction('cancel')}
        onBackup={() => handleBackendAction('backup')}
        onEvidence={() => handleBackendAction('evidence')}
        onReplay={() => handleBackendAction('replay')}
      />
      {showEvidence && <EvidenceReport onClose={() => setShowEvidence(false)} />}
      {showReplay && <ReplayViewer onClose={() => setShowReplay(false)} />}
    </>
  );
}
